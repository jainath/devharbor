import { execFile, execFileSync } from 'node:child_process';
import { promisify } from 'node:util';
import { chmodSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const execFileP = promisify(execFile);

/**
 * Self-signed TLS material for the MCP server's HTTPS mode (see specs/07-mcp-server.md).
 *
 * Generated once with the system openssl (always present on macOS) into the given
 * directory, then reused. SANs cover localhost / 127.0.0.1 / ::1 so the certificate is
 * valid for every way a loopback client addresses us. The extension config lives in a file
 * rather than `-addext` because older LibreSSL builds lack that flag.
 *
 * The directory is injected (the caller passes userData/mcp-tls) so this module stays free
 * of electron imports and unit-tests under plain node. Key generation can be async so it
 * never blocks the Electron main process; a sync entry point exists for tests.
 */

export interface TlsMaterial {
  key: string;
  cert: string;
  certPath: string;
}

const OPENSSL_CNF = `[req]
distinguished_name = dn
x509_extensions = v3_req
prompt = no

[dn]
CN = DevHarbor MCP (localhost)

[v3_req]
basicConstraints = CA:FALSE
keyUsage = digitalSignature, keyEncipherment
extendedKeyUsage = serverAuth
subjectAltName = @alt_names

[alt_names]
DNS.1 = localhost
IP.1 = 127.0.0.1
IP.2 = ::1
`;

function paths(dir: string): { keyPath: string; certPath: string; cnfPath: string } {
  return {
    keyPath: join(dir, 'mcp-key.pem'),
    certPath: join(dir, 'mcp-cert.pem'),
    cnfPath: join(dir, 'openssl.cnf')
  };
}

const OPENSSL_ARGS = (keyPath: string, certPath: string, cnfPath: string): string[] => [
  'req',
  '-x509',
  '-newkey',
  'rsa:2048',
  '-sha256',
  '-days',
  '3650',
  '-nodes',
  '-keyout',
  keyPath,
  '-out',
  certPath,
  '-config',
  cnfPath
];

/** True when both PEMs are already present. */
export function tlsFilesExist(dir: string): boolean {
  const { keyPath, certPath } = paths(dir);
  return existsSync(keyPath) && existsSync(certPath);
}

/**
 * Prepare the directory + a 0600 key file BEFORE openssl runs, so the private key never
 * exists group/world-readable even for a moment: openssl's `-keyout` truncates an existing
 * file in place (BIO fopen "w") and keeps its mode, so pre-creating it 0600 closes the
 * window race-free (no reliance on a process-global umask, which would be unsafe around an
 * async spawn).
 */
function prep(dir: string): { keyPath: string; certPath: string; cnfPath: string } {
  mkdirSync(dir, { recursive: true, mode: 0o700 });
  try {
    chmodSync(dir, 0o700); // re-assert in case the dir pre-existed with looser perms
  } catch {
    /* best-effort */
  }
  const p = paths(dir);
  writeFileSync(p.keyPath, '', { mode: 0o600 });
  writeFileSync(p.cnfPath, OPENSSL_CNF);
  return p;
}

function cleanupAfterFailure(keyPath: string, certPath: string, cnfPath: string, e: unknown): never {
  rmSync(keyPath, { force: true });
  rmSync(certPath, { force: true });
  rmSync(cnfPath, { force: true });
  const detail = e instanceof Error ? e.message : String(e);
  throw new Error(`could not generate a self-signed certificate with openssl (${detail})`);
}

/** Async generation - does NOT block the Electron main process. Throws (fails closed). */
export async function generateTlsMaterial(dir: string): Promise<void> {
  const { keyPath, certPath, cnfPath } = prep(dir);
  try {
    await execFileP('openssl', OPENSSL_ARGS(keyPath, certPath, cnfPath), {
      timeout: 30_000
    });
  } catch (e) {
    cleanupAfterFailure(keyPath, certPath, cnfPath, e);
  }
  rmSync(cnfPath, { force: true });
}

/** Sync generation - only for the unit test / non-hot paths. */
function generateTlsMaterialSync(dir: string): void {
  const { keyPath, certPath, cnfPath } = prep(dir);
  try {
    execFileSync('openssl', OPENSSL_ARGS(keyPath, certPath, cnfPath), {
      stdio: ['ignore', 'ignore', 'pipe'],
      timeout: 30_000
    });
  } catch (e) {
    cleanupAfterFailure(keyPath, certPath, cnfPath, e);
  }
  rmSync(cnfPath, { force: true });
}

/**
 * Load an existing key/cert pair (must already exist). Re-asserts 0600 on the key each load
 * so a pair generated by an older build - or left loose by a crash between generation and
 * chmod - is tightened before use. Throws if the files are missing or malformed.
 */
export function loadTlsMaterial(dir: string): TlsMaterial {
  const { keyPath, certPath } = paths(dir);
  const key = readFileSync(keyPath, 'utf8');
  const cert = readFileSync(certPath, 'utf8');
  if (!key.includes('PRIVATE KEY') || !cert.includes('BEGIN CERTIFICATE')) {
    throw new Error(
      `TLS files at ${dir} look invalid. Delete the mcp-key.pem/mcp-cert.pem pair to regenerate.`
    );
  }
  try {
    chmodSync(keyPath, 0o600);
  } catch {
    /* best-effort */
  }
  return { key, cert, certPath };
}

/** Sync generate-if-missing + load. Blocks; used by tests and any non-hot caller. */
export function ensureTlsMaterial(dir: string): TlsMaterial {
  if (!tlsFilesExist(dir)) generateTlsMaterialSync(dir);
  return loadTlsMaterial(dir);
}
